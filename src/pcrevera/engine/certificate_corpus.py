# --- the arithmetic of BOUNDS.md section 2 ---


def _norm(base: int, coefs) -> Poly:
    """The canonical form, and the saturation point the checker refuses at.

    Python counts as high as it likes and a counter does not, so a bound this
    arithmetic could write down and the engine could not hold is refused here
    rather than later: `price` promises a certificate the checker accepts, and
    the checker answers `CrOverflow` for exactly this.
    """
    if base > CAP or any(one > CAP for one in coefs):
        raise ValueError("a bound past what a counter holds")
    return canonical(base, coefs)


def padd(a: Poly, b: Poly) -> Poly:
    return _norm(max(a.base, b.base), [coef(a, d) + coef(b, d) for d in DEGREES])


def pmul(a: Poly, b: Poly) -> Poly:
    out = [0] * len(DEGREES)
    for left in DEGREES:
        for right in DEGREES:
            product = coef(a, left) * coef(b, right)
            if product == 0:
                continue
            if left + right > spec.MAX_DEGREE:
                raise ValueError("a product past the top power the struct holds")
            out[left + right] += product
    return _norm(a.base * b.base, out)


def flat(p: Poly) -> int | None:
    """The one number this bound is, or None if it is not one number."""
    if p.base != 1 or any(coef(p, d) for d in DEGREES[1:]):
        return None
    return coef(p, 0)


def const(value: int) -> Poly:
    return _norm(1, [value])


STEP = Poly((0, 1))
"""n + 1."""


# --- pricing a region tree, which is BOUNDS.md sections 3 and 4 ---


@dataclass
class Acc:
    work: Poly = ZERO
    stack: Poly = ZERO
    trail: Poly = ZERO
    flow: Poly = ZERO


@dataclass(frozen=True)
class Program:
    """The facts the checker is given, read back out of a compiled pattern."""

    code: tuple[tuple[str, int, int], ...]
    reps: tuple[dict, ...]
    regions: tuple[Region, ...]
    ncap: int
    nregs: int


def read(built: CompiledPattern) -> Program:
    re = built.re
    return Program(
        code=tuple(
            (_variant_of(one, "op"), one.fields["arg"], one.fields["alt"])
            for one in _items(re.fields["code"])
        ),
        reps=tuple(
            {
                key: value.variant if isinstance(value, Tag) else value
                for key, value in one.fields.items()
            }
            for one in _items(re.fields["reps"])
        ),
        regions=tuple(
            Region(
                kind=_variant_of(one, "kind"),
                parent=one.fields["parent"],
                lo=one.fields["lo"],
                hi=one.fields["hi"],
            )
            for one in _items(re.fields["regions"])
        ),
        ncap=re.fields["ncap"],
        nregs=re.fields["nregs"],
    )


def _items(value) -> list[StructValue]:
    assert isinstance(value, Frozen)
    inner = value.inner
    assert isinstance(inner, Seq)
    return [one for one in inner.items if isinstance(one, StructValue)]


def _variant_of(one: StructValue, name: str) -> str:
    tag = one.fields[name]
    assert isinstance(tag, Tag)
    return tag.variant


def _span(prog: Program, priced, kids: list[int], lo: int, hi: int, acc: Acc) -> None:
    """Read a stretch of bytecode, charging every instruction to the flow."""
    tree = prog.regions
    pc = lo
    while pc < hi:
        if kids and tree[kids[0]].lo == pc:
            at = kids.pop(0)
            kid = priced[at]
            if tree[at].hi <= pc or tree[at].hi > hi:
                raise ValueError(f"region {at} is not a child of this span")
            acc.work = padd(acc.work, pmul(acc.flow, kid.work))
            acc.stack = padd(acc.stack, pmul(acc.flow, kid.stack))
            acc.trail = padd(acc.trail, pmul(acc.flow, kid.trail))
            acc.flow = pmul(acc.flow, kid.flow)
            pc = tree[at].hi
            continue
        op = prog.code[pc][0]
        if op in SIMPLE_OPS:
            acc.work = padd(acc.work, acc.flow)
        elif op == "OpSave":
            acc.work = padd(acc.work, acc.flow)
            acc.trail = padd(acc.trail, acc.flow)
        elif op == "OpAccept":
            acc.work = padd(acc.work, acc.flow)
            acc.flow = ZERO
        else:
            raise ValueError(f"{op} at {pc} belongs to a region, not to a span")
        pc += 1


def _alt(priced, kids: list[int]) -> Acc:
    """Every branch is tried, and every one but the last leaves by a jump."""
    acc = Acc()
    for index, child in enumerate(kids):
        kid = priced[child]
        acc.work = padd(acc.work, kid.work)
        acc.stack = padd(acc.stack, kid.stack)
        acc.trail = padd(acc.trail, kid.trail)
        acc.flow = padd(acc.flow, kid.flow)
        if index < len(kids) - 1:
            acc.work = padd(acc.work, padd(const(1), kid.flow))
            acc.stack = padd(acc.stack, const(1))
    return acc


def _repeat(prog: Program, priced, kids: list[int], at: int) -> Acc:
    here = prog.regions[at]
    lo, hi = here.lo, here.hi
    head = prog.code[lo]
    acc = Acc(ZERO, ZERO, ZERO, const(1))
    if head[0] == "OpSplit":
        _span(prog, priced, kids, lo + 1, hi, acc)
        acc.work = padd(acc.work, const(1))
        acc.stack = padd(acc.stack, const(1))
        acc.flow = padd(acc.flow, const(1))
        return acc

    rep = prog.reps[head[1]]
    _span(prog, priced, kids, lo + 3, hi - 1, acc)
    ways = flat(acc.flow)
    if ways is None:
        raise ValueError("a repeat body whose ambiguity grows with the subject")
    bounded = rep["hi"] != spec.NONE
    ceiling = max(rep["lo"], rep["hi"]) if bounded else rep["lo"]
    # One more than the iteration count, because what is counted is passes
    # through the head, and the pass that finds the count spent is a pass.
    rounds = const(ceiling + 1) if bounded else Poly((rep["lo"] + 1, 1))
    if ways > 1:
        exponent = ceiling + 1 if bounded else rep["lo"] + 2
        raised = ways**exponent
        if raised > CAP:
            raise ValueError("a pass count past what a counter holds")
        rounds = const(raised) if bounded else Poly((raised,), ways)

    body, per = acc, const(ways)
    return Acc(
        work=padd(const(1), pmul(rounds, padd(padd(const(2), body.work), per))),
        stack=pmul(rounds, padd(const(1), body.stack)),
        trail=padd(const(1), pmul(rounds, padd(padd(const(1), per), body.trail))),
        flow=pmul(rounds, padd(const(1), per)),
    )


def price(prog: Program) -> Certificate:
    """The smallest certificate the checker accepts for this program.

    Bottom up, because a region is priced from what its children cost, which is
    the same induction the checker walks and the same one Layer A will. It is
    the same answer `engine/analyzer.py` reaches in TIR, reached again here in
    Python and never run in production, so that an exact-minimum case really is
    exact, a mutation of one really is a unit short, and the analyzer has
    something to be compared against that is not itself.
    """
    tree = prog.regions
    kids: dict[int, list[int]] = {at: [] for at in range(len(tree))}
    for at, region in enumerate(tree):
        if at:
            kids[region.parent].append(at)
    priced: dict[int, Acc] = {}
    for at in reversed(range(len(tree))):
        region = tree[at]
        mine = list(kids[at])
        if region.kind in SEQUENCE:
            acc = Acc(ZERO, ZERO, ZERO, const(1))
            _span(prog, priced, mine, region.lo, region.hi, acc)
        elif region.kind == "RkAlt":
            acc = _alt(priced, mine)
            mine = []
        elif region.kind == "RkRepeat":
            acc = _repeat(prog, priced, mine, at)
        else:
            raise ValueError(f"no composition rule for {region.kind}")
        if mine:
            raise ValueError(f"region {at} left children unpriced")
        priced[at] = acc

    root = priced[0]
    novec = (prog.ncap + 1) * 2
    setup = (prog.nregs + novec) * spec.REG_SIZE
    deliver = novec * spec.REG_SIZE
    reset = prog.nregs * spec.REG_SIZE
    scratch = ZERO
    for quantity, esize in (("stack", spec.BT_SIZE), ("trail", spec.UNDO_SIZE)):
        held = getattr(root, quantity)
        capacity = (
            ZERO
            if held == ZERO
            else padd(const(spec.GROW_MIN), pmul(held, const(spec.GROW_FACTOR)))
        )
        scratch = padd(scratch, pmul(capacity, const(esize)))
    # The 3 and the 2 are the two bounds BOUNDS.md section 5 derives from the
    # growth schedule rather than numbers the matcher holds: the buffers a
    # doubling run allocates come to twice its final reservation and the ones
    # it copies out of to one more, and holding both at once is what makes the
    # memory peak twice the reservation.
    cost = padd(
        const(setup + deliver),
        padd(
            pmul(
                padd(
                    const(reset),
                    padd(root.work, pmul(root.trail, const(spec.REG_SIZE))),
                ),
                STEP,
            ),
            pmul(scratch, const(3)),
        ),
    )
    return Certificate(
        prices=tuple(
            Price(work=one.work, outs=one.flow, stack=one.stack, trail=one.trail)
            for one in (priced[at] for at in range(len(tree)))
        ),
        cost=cost,
        stack=root.stack,
        trail=root.trail,
        # The delivered answer is resident alongside the scratch, which is
        # why `deliver` appears in the memory bound as well as the cost.
        mem=padd(const(setup + deliver), pmul(scratch, const(2))),
        complexity=classify(cost),
    )


def classify(cost: Poly) -> str:
    """BOUNDS.md section 6, which is a rule about the bound rather than the pattern.

    Linear means the cost really is at most c * (n + 1), so it is read off the
    shape of the polynomial: base one, and nothing above the first power.
    """
    flatter = cost.base == 1 and not any(coef(cost, d) for d in DEGREES[2:])
    return "CcLinear" if flatter else "CcNotProvenLinear"


# --- the cases ---


@dataclass(frozen=True)
class Case:
    """One certificate, the program it prices, and the verdict it has to draw."""

    name: str
    note: str
    check: str
    pattern: bytes
    cert: Certificate
    config: str = "CfgBacktrack"
    regions: tuple[Region, ...] | None = None
    """A region table to put in place of the one the compiler emitted.

    Every rule that holds the tree to the bytecode needs a tree that does not,
    and since the compiler is what emits trees now, the only way to write one
    down is to hand it to the checker where the compiler's would have been.
    """
    bounds: tuple[dict, ...] = field(default=(), compare=False)
    """What the file records this certificate evaluating to.

    Out of the comparison, so that the round-trip check is about the case and
    not about numbers the case never claimed.
    """
    shape: str = "CrOk"
    """What the half of the checker that takes no certificate said.

    The checker asks two questions and only the second needs a certificate:
    does this tree describe this program, and does this certificate bound it.
    Compilation runs the first on its own, so which half answers a case is part
    of what the case says, and most of them say `CrOk` — nothing is wrong with
    the program, and the argument is about the numbers.

    Written rather than derived from `check`, because the verdict alone does
    not settle it. `CrShape` is drawn for a program the checker cannot read and
    for a certificate field naming no variant of its enum, and those are
    opposite answers to this question.
    """

    def subject(self) -> CompiledPattern:
        """The compiled pattern the checker is handed, doctored tree and all."""
        built = compiled(self.pattern)
        return built if self.regions is None else built.with_regions(self.regions)


ENGINE = Engine()


@functools.lru_cache(maxsize=None)
def attempted(pattern: bytes):
    """What compiling this pattern came to, remembered.

    Compiling goes through the reference interpreter, which is slow enough that
    the corpus and its tests compiling `abc` two dozen times each is worth
    avoiding. A compiled pattern is immutable, so one serves every caller, and
    so does a refusal.
    """
    return ENGINE.compile_pattern(pattern)


def compiled(pattern: bytes) -> CompiledPattern:
    """The same, for a caller who has no use for a pattern that does not."""
    built = attempted(pattern)
    if not isinstance(built, CompiledPattern):
        raise AssertionError(f"{pattern!r} does not compile: {built}")
    return built


def region(kind: str, parent: int, lo: int, hi: int) -> Region:
    return Region(kind=kind, parent=parent, lo=lo, hi=hi)


def root(hi: int) -> Region:
    return region("RkRoot", spec.NONE, 0, hi)


def minimal(pattern: bytes) -> Certificate:
    """The exact-minimum certificate for a pattern's own region tree."""
    return price(read(compiled(pattern)))


def lockstep(pattern: bytes) -> Certificate:
    """The Pike closed form of BOUNDS.md section 9, stated a second time.

    The same relationship `price` has to sections 1 through 8: an independent
    Python restatement the engine's own numbers are compared against, so that
    the exact-minimum cases really are exact and the one-unit-lower mutations
    really are one unit short.
    """
    built = compiled(pattern)
    code = items(built.re.fields["code"])
    instructions = len(code)
    slots = 2 * (built.re.fields["ncap"] + 1)
    block = spec.REG_SIZE * slots
    words = instructions // 8 + 1
    saves = sum(
        1 for inst in code if variant_of(inst.fields["op"]) == "OpSave"
    )

    def capacity(entries: int) -> int:
        return 0 if entries == 0 else spec.GROW_MIN + spec.GROW_FACTOR * entries

    blocks = 4 * instructions + 2
    reserved = (
        2 * spec.TH_SIZE * capacity(instructions)
        + spec.TH_SIZE * capacity(2 * instructions)
        + 2 * spec.REG_SIZE * capacity(blocks)
        + spec.REG_SIZE * capacity(blocks * slots)
    )
    setup = block + words
    position = 2 * instructions + (saves + 2) * block + words
    return Certificate(
        prices=(),
        cost=canonical(1, (setup + block + 3 * reserved, position)),
        stack=ZERO,
        trail=ZERO,
        mem=canonical(1, (setup + block + 2 * reserved,)),
        config="CfgPike",
        complexity="CcLinear",
    )


def unpriced(count: int) -> Certificate:
    """A certificate that claims nothing, for the cases about the tree itself."""
    return Certificate(prices=(Price(),) * count)


def less(cert: Certificate, *path) -> Certificate:
    """The same certificate with one coefficient a single unit lower.

    The path is either a whole-pattern bound and a power — `("cost", 1)` — or a
    region, one of the four things it is priced for, and a power.
    """
    *where, degree = path
    if len(where) == 1:
        return replace(cert, **{where[0]: _drop(getattr(cert, where[0]), degree)})
    at, quantity = where
    prices = list(cert.prices)
    prices[at] = replace(
        prices[at], **{quantity: _drop(getattr(prices[at], quantity), degree)}
    )
    return replace(cert, prices=tuple(prices))


def _shift(p: Poly, degree: int, delta: int) -> Poly:
    if coef(p, degree) + delta < 0:
        raise ValueError(f"there is no unit at degree {degree} to take away")
    coefs = [coef(p, d) for d in DEGREES]
    coefs[degree] += delta
    return _norm(p.base, coefs)


def _drop(p: Poly, degree: int) -> Poly:
    return _shift(p, degree, -1)


def more(cert: Certificate, bound: str, degree: int) -> Certificate:
    """The same certificate with one whole-pattern coefficient a unit higher.

    Only meaningful for the bounds held to equality, which is what BOUNDS.md
    section 5 says about the stack and the trail; the others may overestimate
    freely.
    """
    return replace(cert, **{bound: _shift(getattr(cert, bound), degree, 1)})


def claiming(cert: Certificate, **over) -> Certificate:
    return replace(cert, **over)


KEPT = rb"\R"
"""What keeps a counted repetition in counter form.

BOUNDS.md section 4.4 prices the five-part counter header, and after the
quantifier lowering of DESIGN.md section 4.3 that header is only emitted for a
pure star or for a pattern the lowering declined. So every case below that is
about the *bounded* half of section 4.4 carries one of the three carve-outs,
and this is the cheapest of them to write: `\\R` refuses the whole pattern the
lowering, opens no region of its own and adds one instruction to the root, so
the counted repetition beside it is priced exactly as section 4.4 says.

A trailing `\\R` in a pattern here therefore means "and this is why the
quantifier still has a counter", never "and here is what `\\R` does"."""

