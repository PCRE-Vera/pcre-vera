def _context_limits(cost=CTX_COST, stack=CTX_STACK, memory=CTX_MEMORY) -> Limits:
    return Limits(cost=cost, stack=stack, memory=memory)


def _creation(built, name: str, want: int, **args):
    """One creation row, run and held to the outcome the case wrote down.

    The context comes back with the row so the case's own creation — the
    first rung of the ladder — can also be the one the calls replay on,
    rather than being made twice through the interpreter.
    """
    asked = {
        "config": spec.MC_DEFAULT,
        "maxlen": 0,
        "cost": CTX_COST,
        "stack": CTX_STACK,
        "memory": CTX_MEMORY,
        **args,
    }
    status, held = ENGINE.create_context(
        built,
        max_subject_len=asked["maxlen"],
        limits=_context_limits(asked["cost"], asked["stack"], asked["memory"]),
        match_config=asked["config"],
    )
    if status != want:
        raise AssertionError(f"{name}: creation answers {status}, the case says {want}")
    row = {**asked, "status": status}
    if held is not None:
        row["memcap"] = held.memory
    return row, held


def contexts() -> list[dict]:
    """Every context case: the creation ladder, then one context's life."""
    out = []
    for case in CONTEXTS:
        built = compiled(case.pattern)
        first, held = _creation(built, case.name, case.status, maxlen=case.maxlen)
        rows = [first]
        for refusal in (
            {"config": spec.MC_MEMO},
            {"maxlen": spec.MAX_LENGTH + 1},
        ):
            row, _ = _creation(
                built,
                case.name,
                spec.BAD_INPUT,
                **{"maxlen": case.maxlen, **refusal},
            )
            rows.append(row)
        if case.status == spec.OK:
            need = first["memcap"]
            # The reservation is the memory accessor's answer made physical,
            # which is the equality the whole design leans on; a backend
            # whose two numbers drift apart must fail here.
            answered = ENGINE.worst_case(built, "mem", case.maxlen)
            if answered != (spec.OK, need):
                raise AssertionError(
                    f"{case.name}: the context reserves {need}, the accessor "
                    f"answers {answered}"
                )
            for starved in ("memory", "cost"):
                row, _ = _creation(
                    built,
                    case.name,
                    spec.RESOURCE_EXCEEDED,
                    maxlen=case.maxlen,
                    **{starved: need - 1},
                )
                rows.append(row)

        calls = []
        if case.calls:
            assert held is not None
            for one in case.calls:
                got = ENGINE.context_match(
                    held,
                    one.subject,
                    start=one.start,
                    cost_limit=one.cost,
                    stack_limit=one.stack,
                )
                if statused(got) != one.status:
                    raise AssertionError(
                        f"{case.name}: {one.subject!r} answers {got!r}, "
                        f"the case says {one.status}"
                    )
                row = {
                    "subject": one.subject.hex(),
                    "start": one.start,
                    "cost": one.cost,
                    "stack": one.stack,
                    "status": one.status,
                }
                if isinstance(got, Match):
                    row["ovector"] = list(got.ovector)
                calls.append(row)

        out.append(
            {
                "name": case.name,
                "note": case.note,
                "pattern": case.pattern.hex(),
                "maxlen": case.maxlen,
                "creations": rows,
                "calls": calls,
            }
        )
    return out


def load_contexts(path=PATH) -> list[dict]:
    """The context entries of the committed corpus, as the runners read them."""
    return conformance.section(conformance.read(path), "contexts", path)


def _ordinal(enum: str, variant: str) -> int:
    return program().enum_map[enum].ordinal(variant)


def _variant(enum: str, ordinal: int) -> str:
    return program().enum_map[enum].variants[ordinal]


def _poly(p: Poly) -> dict:
    return {"base": p.base, **{f"c{d}": coef(p, d) for d in DEGREES}}


def _read_poly(body: dict) -> Poly:
    return _norm(body["base"], [body[f"c{d}"] for d in DEGREES])


def _region(one: Region) -> dict:
    return {
        "kind": _ordinal("Rk", one.kind),
        "parent": one.parent,
        "lo": one.lo,
        "hi": one.hi,
    }


def _read_region(body: dict) -> Region:
    return Region(
        kind=_variant("Rk", body["kind"]),
        parent=body["parent"],
        lo=body["lo"],
        hi=body["hi"],
    )


def _cert(cert: Certificate) -> dict:
    return {
        "config": _ordinal("Cfg", cert.config),
        "complexity": _ordinal("Cc", cert.complexity),
        "cost": _poly(cert.cost),
        "stack": _poly(cert.stack),
        "trail": _poly(cert.trail),
        "mem": _poly(cert.mem),
        "prices": [
            {
                "work": _poly(one.work),
                "outs": _poly(one.outs),
                "stack": _poly(one.stack),
                "trail": _poly(one.trail),
            }
            for one in cert.prices
        ],
    }


def _bounds(cert: Certificate) -> list[dict]:
    return [
        {"n": length, **{key: ENGINE.bound(cert, which, length) for key, which in KINDS}}
        for length in LENGTHS
    ]


def patterns() -> list[bytes]:
    """Every pattern this corpus names, in the order the lists name them.

    The migration report reads them, and it wants the pattern rather than the
    case: what a case says about a certificate is its own business, and what
    the report asks is what compilation decided about the pattern.
    """
    out: list[bytes] = []
    for one in (*CASES, *ANALYSES, *ACCESSES, *CONTEXTS):
        out.append(one.pattern)
    return list(dict.fromkeys(out))


def cases() -> list[dict]:
    """Every case, with the verdict and the bounds the reference interpreter gives."""
    out = []
    for case in CASES:
        built = case.subject()
        verdict = ENGINE.check_certificate(built, case.cert, case.config)
        if verdict != case.check:
            raise AssertionError(
                f"{case.name}: the checker says {verdict}, the case says {case.check}"
            )
        shape = ENGINE.check_shape(built)
        if shape != case.shape:
            raise AssertionError(
                f"{case.name}: cert_shape says {shape}, the case says {case.shape}"
            )
        entry = {
            "name": case.name,
            "note": case.note,
            "pattern": case.pattern.hex(),
            "config": _ordinal("Cfg", case.config),
            "cert": _cert(case.cert),
            "check": _ordinal("Cr", case.check),
            "shape": _ordinal("Cr", shape),
            "bounds": _bounds(case.cert),
        }
        if case.regions is not None:
            entry["regions"] = [_region(one) for one in case.regions]
        out.append(entry)
    return out


def analyses() -> list[dict]:
    """Every analysis, with the certificate compilation really came up with.

    The verdict comes from running the analyzer again and the certificate from
    the slot compilation filled, so an engine whose two answers disagreed would
    be caught writing this file rather than reading it.
    """
    out = []
    for one in ANALYSES:
        built = compiled(one.pattern)
        found, again = ENGINE.analyze(built)
        cert = built.certificate
        if again != cert:
            raise AssertionError(
                f"{one.name}: the certificate on the compiled pattern is not the "
                "one the analyzer produces"
            )
        claimed = None if cert is None else cert.complexity
        if (found, claimed) != (one.found, one.complexity):
            raise AssertionError(
                f"{one.name}: the analyzer says {found} and claims {claimed}, "
                f"the entry says {one.found} and {one.complexity}"
            )
        out.append(
            {
                "name": one.name,
                "note": one.note,
                "pattern": one.pattern.hex(),
                "found": _ordinal("Ar", found),
                "complexity": None if cert is None else _ordinal("Cc", claimed),
                "bounds": [] if cert is None else _bounds(cert),
            }
        )
    return out


def corpus() -> dict:
    return conformance.document(
        NOTE,
        cases(),
        analyses=analyses(),
        accessors=accesses(),
        contexts=contexts(),
    )


def corpus_text() -> str:
    return conformance.text(corpus())


def load(path=PATH) -> list[Case]:
    """The committed corpus, decoded back into the cases it was written from.

    The Python runner reads the file the other two read rather than the objects
    it was generated from, so an encoding that lost something fails here
    instead of quietly agreeing with itself.
    """
    out: list[Case] = []
    for entry in conformance.read(path)["cases"]:
        body = entry["cert"]
        held = entry.get("regions")
        out.append(
            Case(
                name=entry["name"],
                note=entry["note"],
                check=_variant("Cr", entry["check"]),
                shape=_variant("Cr", entry["shape"]),
                pattern=bytes.fromhex(entry["pattern"]),
                config=_variant("Cfg", entry["config"]),
                regions=None if held is None else tuple(_read_region(o) for o in held),
                cert=Certificate(
                    prices=tuple(
                        Price(
                            work=_read_poly(one["work"]),
                            outs=_read_poly(one["outs"]),
                            stack=_read_poly(one["stack"]),
                            trail=_read_poly(one["trail"]),
                        )
                        for one in body["prices"]
                    ),
                    cost=_read_poly(body["cost"]),
                    stack=_read_poly(body["stack"]),
                    trail=_read_poly(body["trail"]),
                    mem=_read_poly(body["mem"]),
                    config=_variant("Cfg", body["config"]),
                    complexity=_variant("Cc", body["complexity"]),
                ),
                bounds=tuple(entry["bounds"]),
            )
        )
    return out


def load_accessors(path=PATH) -> list[dict]:
    """The accessor entries of the committed corpus, as the runners read them.

    Raw dictionaries rather than dataclasses, deliberately: the Go and
    JavaScript runners read this section as plain decoded JSON against their
    public wrappers, and the Python runner should be the same kind of reader
    rather than one with a private schema the other two lack.
    """
    return conformance.section(conformance.read(path), "accessors", path)


def load_analyses(path=PATH) -> list[Analysis]:
    """The other half of the committed corpus, decoded the same way."""
    return [
        Analysis(
            name=entry["name"],
            note=entry["note"],
            pattern=bytes.fromhex(entry["pattern"]),
            found=_variant("Ar", entry["found"]),
            complexity=(
                None
                if entry["complexity"] is None
                else _variant("Cc", entry["complexity"])
            ),
            bounds=tuple(entry["bounds"]),
        )
        for entry in conformance.section(conformance.read(path), "analyses", path)
    ]


