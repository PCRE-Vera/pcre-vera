"""What the resource analysis has to answer, in every language.

`certificate.py` is the checker and `analyzer.py` is the analyzer; this is the
corpus both are held to. It sits beside them rather than beside the printers,
because its subject is the engine rather than the lowering — the generator
reaches across for it the same way it reaches for the wave 1 restatement in
`oracle/conformance.py`.

It comes in two halves, because the two halves of DESIGN.md section 5 are
reached differently.

The `cases` are the checker's, and they exist because a certificate has no way
in through the public API — which is exactly the gap DESIGN.md section 8 asks
these corpora to close. Without them the checker would be the one piece of the
engine that both backends carried and neither ran, on the link the design calls
tested rather than proved. A case names a pattern rather than a bytecode
listing, so every runner compiles it with the engine it has and the checker is
handed the program that engine would really run. Two runners that disagree
about the bytecode therefore disagree here, which is the point.

The region tree is the compiler's — it emits one while it still has the AST
in hand — so a case names a pattern and gets the tree that pattern really
compiles to. The cases about trees that are not trees hand the checker one of
their own instead, since no compiler would emit those and the rules that refuse
them still have to be exercised.

The `analysis` entries are the analyzer's, and they need no way in at all:
compiling a pattern runs it. What they record is what came out — the class
claimed and the three bounds — or that nothing did, for the patterns whose
bounds have no shape the arithmetic of section 2 can write down. Not the price
of every region: that is a great many numbers to pin from the side, and the
checker already holds each of them to the bytecode, so a backend whose analyzer
under-prices a region never reaches this file. Python asks the stronger
question, which is that the whole certificate is exactly what `price` below
computes.

The certificates in the first half are built by `price` below, which is
BOUNDS.md written a second time in Python. That is deliberate. Writing out four
polynomials per region by hand would be transcription, and transcription is
where a corpus quietly stops describing anything; computing them from the rules
means the exact-minimum cases really are exact, and the one-unit-lower
mutations really are one unit short. It is also the independent statement the
analyzer is compared against, which is why it stays a reference and never
becomes the production path. What is hand-written is the verdict of every case,
which half of the checker drew it, and whether each analysis finds a bound at
all — all checked at generation time, so an engine that changed its mind breaks
the build instead of rewriting the file it is supposed to be held to.
"""

