def _ordinal(enum: str, variant: str) -> int:
    return program().enum_map[enum].ordinal(variant)


def _variant(enum: str, ordinal: int) -> str:
    return program().enum_map[enum].variants[ordinal]


def _sum(one: Sum) -> dict:
    return {"first": one.first, "count": one.count}


def _cert(cert: Certificate) -> dict:
    return {
        "config": _ordinal("Cfg", cert.config),
        "complexity": _ordinal("Cc", cert.complexity),
        "regions": [
            {
                "kind": _ordinal("Rk", region.kind),
                "parent": region.parent,
                "lo": region.lo,
                "hi": region.hi,
                "cost": _sum(region.cost),
                "stack": _sum(region.stack),
                "mem": _sum(region.mem),
            }
            for region in cert.regions
        ],
        "terms": [
            {"coef": one.coef, "base": one.base, "degree": one.degree}
            for one in cert.terms
        ],
    }


def cases() -> list[dict]:
    """Every case, with the verdict and the bounds the reference interpreter gives."""
    engine = Engine()
    out = []
    for case in CASES:
        verdict = engine.check_certificate(case.cert, case.codelen)
        if verdict != case.check:
            raise AssertionError(
                f"{case.name}: the checker says {verdict}, the case says {case.check}"
            )
        entry = {
            "name": case.name,
            "note": case.note,
            "codelen": case.codelen,
            "cert": _cert(case.cert),
            "check": _ordinal("Cr", case.check),
            "bounds": [
                {
                    "n": length,
                    **{key: engine.bound(case.cert, which, length) for key, which in KINDS},
                }
                for length in LENGTHS
            ],
        }
        out.append(entry)
    return out


def corpus() -> dict:
    return conformance.document(NOTE, cases())


def corpus_text() -> str:
    return conformance.text(corpus())


def load(path=PATH) -> list[Case]:
    """The committed corpus, decoded back into the cases it was written from.

    The Python runner reads the file the other two read rather than the objects
    it was generated from, so an encoding that lost something fails here
    instead of quietly agreeing with itself.
    """
    cases: list[Case] = []
    for entry in conformance.read(path)["cases"]:
        body = entry["cert"]
        cases.append(
            Case(
                name=entry["name"],
                note=entry["note"],
                check=_variant("Cr", entry["check"]),
                cert=Certificate(
                    regions=tuple(
                        Region(
                            kind=_variant("Rk", one["kind"]),
                            parent=one["parent"],
                            lo=one["lo"],
                            hi=one["hi"],
                            cost=Sum(**one["cost"]),
                            stack=Sum(**one["stack"]),
                            mem=Sum(**one["mem"]),
                        )
                        for one in body["regions"]
                    ),
                    terms=tuple(Term(**one) for one in body["terms"]),
                    config=_variant("Cfg", body["config"]),
                    complexity=_variant("Cc", body["complexity"]),
                ),
                codelen=entry["codelen"],
                bounds=tuple(entry["bounds"]),
            )
        )
    return cases


