PATH = CONFORMANCE_DIR / "certificates.json"

NOTE = (
    "Generated by pcretruste.engine.certificate_corpus. Each case hands the engine's "
    "bound-certificate checker one certificate and asks for the three bounds it "
    "prices, at every subject length below. Every implementation of the engine has "
    "to give exactly these answers: the same verdict, and the same number or the "
    "same refusal. A bound of null is the ExceedsBudget of DESIGN.md section 2.4, "
    "which is a refusal rather than a number and never a saturated counter."
)

CODE = 6
"""Instructions in the pattern these certificates claim to price."""

LENGTHS = (0, 1, 2, 10, 53, 65535, CAP)
"""Subject lengths every case is evaluated at.

Small ones because that is where a bound is a usable number, 53 because it is
where a doubling term runs out of counter, and the cap because a bound has to
refuse rather than wrap at the far end of the range.
"""

KINDS = (("cost", "BkCost"), ("stack", "BkStack"), ("mem", "BkMem"))
"""What the file calls each bound, and what the engine calls the same one."""


@dataclass(frozen=True)
class Case:
    """One certificate, and the verdict it has to draw.

    The verdict is written down rather than recorded, so a checker that changed
    its mind breaks generation loudly instead of quietly rewriting the file it
    is supposed to be held to. The bounds are recorded, because writing out
    three numbers at seven subject lengths by hand would be transcription
    rather than specification; `tests/test_certificate.py` states the ones
    that say something on their own.
    """

    name: str
    note: str
    check: str
    cert: Certificate
    codelen: int = CODE
    bounds: tuple[dict, ...] = field(default=(), compare=False)
    """What the file records this certificate evaluating to.

    Out of the comparison, so that the round-trip check is about the case and
    not about numbers the case never claimed.
    """


def root(**over) -> Region:
    """The region every certificate needs: the whole program, no parent."""
    return Region(**{"kind": "RkRoot", "parent": spec.NONE, "lo": 0, "hi": CODE, **over})


def priced(*terms: Term, complexity: str = "CcNotProvenLinear", **over) -> Certificate:
    """A root-only certificate whose cost is the sum of these terms."""
    return Certificate(
        regions=(root(cost=Sum(0, len(terms)), **over),),
        terms=terms,
        complexity=complexity,
    )


