"""The lowering probe: a small TIR program aimed at what the printers can get wrong.

The engine and its 264-case corpus exercise the backends broadly, but not
squarely. Every multiplication the engine performs is on small offsets, so a
JavaScript printer that forgot `Math.imul` would pass the whole corpus and then
be wrong the first time a product went past 2^53. The same goes for a struct
read that aliases where it should copy, a growth schedule that rounds
differently, and a coercion applied to the wrong operand.

So this program does those things on purpose, with operands chosen to sit on
the boundary, and the conformance corpus of DESIGN.md section 8 carries the
answers. One entry point keeps the runner in each language down to a single
call:

    probe(kind, a, b) -> counter

`kind` picks the operation, `a` and `b` are the operands as counters, and the
answer comes back as a counter — through a cast to u32 where the bit pattern
is what matters, and packed two-at-a-time by `shape` where a branch has a
pair to report.
"""

