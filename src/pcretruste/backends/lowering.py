@branch("and-short-circuits", ONE_SIZE)
def _and_short_circuits(f: FuncBuilder, x: Probe) -> None:
    # The right operand indexes past the end whenever the left is false, so an
    # implementation that evaluates both traps instead of answering.
    bag = f.let("sc_bag", vec(u32, 40))
    f.push(bag, u32(7))
    f.ret(land(x.au < bag.len(), bag.at(x.au) == u32(7)).cast(counter))


