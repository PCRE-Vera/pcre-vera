# --- sequences: the growth schedule of section 11, read back through cap ---


@branch("push-capacity", ONE_SIZE)
def _push_capacity(f: FuncBuilder, x: Probe) -> None:
    bag = f.let("push_bag", vec(u32, 40))
    i = f.let("push_i", u32, u32(0))
    with f.while_(i < x.au, (x.au - i).cast(counter)):
        f.push(bag, i)
        f.set(i, i + u32(1))
    f.ret(shape(bag.cap(), bag.len()))


@branch("reserve-then-push", _pairs(SIZES, SIZES))
def _reserve_then_push(f: FuncBuilder, x: Probe) -> None:
    bag = f.let("res_bag", vec(u32, 40))
    f.reserve(bag, x.bu)
    i = f.let("res_i", u32, u32(0))
    with f.while_(i < x.au, (x.au - i).cast(counter)):
        f.push(bag, i)
        f.set(i, i + u32(1))
    f.ret(shape(bag.cap(), bag.len()))


@branch("truncate-keeps-capacity", [(a, b) for a in SIZES for b in SIZES if b <= a])
def _truncate_keeps_capacity(f: FuncBuilder, x: Probe) -> None:
    bag = f.let("trunc_bag", vec(u32, 40))
    i = f.let("trunc_i", u32, u32(0))
    with f.while_(i < x.au, (x.au - i).cast(counter)):
        f.push(bag, i)
        f.set(i, i + u32(1))
    f.truncate(bag, x.bu)
    f.ret(shape(bag.cap(), bag.len()))


@branch("pop-gives-the-last", [(a, 0) for a in SIZES if a >= 1])
def _pop_gives_the_last(f: FuncBuilder, x: Probe) -> None:
    bag = f.let("pop_bag", vec(u32, 40))
    i = f.let("pop_i", u32, u32(0))
    with f.while_(i < x.au, (x.au - i).cast(counter)):
        f.push(bag, i + u32(100))
        f.set(i, i + u32(1))
    last = f.let("pop_last", u32, u32(0))
    f.pop(bag, last)
    f.ret(shape(last, bag.len()))


@branch("copy-is-deep")
def _copy_is_deep(f: FuncBuilder, x: Probe) -> None:
    original = f.let("copy_from", vec(u32, 40))
    f.push(original, x.au)
    f.push(original, x.bu)
    duplicate = f.let("copy_to", vec(u32, 40))
    f.copy(duplicate, original)
    f.set(original.at(u32(0)), u32(777))
    # A copy has capacity equal to its length, whatever the original's was.
    f.ret(shape(duplicate.at(u32(0)), duplicate.cap()))


@branch("freeze-empties-the-source")
def _freeze_empties_the_source(f: FuncBuilder, x: Probe) -> None:
    original = f.let("freeze_from", vec(u32, 40))
    f.push(original, x.au)
    kept = f.let("freeze_to", frozen(vec(u32, 40)))
    f.freeze(kept, original)
    f.ret(shape(kept.at(u32(0)), original.len()))


