# --- switch, which Go prints as a switch and JavaScript as an if-chain ---


@branch("switch-covers-the-enum", ONE_SIZE)
def _switch_covers_the_enum(f: FuncBuilder, x: Probe) -> None:
    picked = f.let("sc_picked", x.Colour)
    with f.if_(x.au == u32(0)):
        f.set(picked, x.Colour.Red)
    with f.else_():
        with f.if_(x.au == u32(1)):
            f.set(picked, x.Colour.Green)
        with f.else_():
            f.set(picked, x.Colour.Blue)
    answer = f.let("sc_answer", u32, u32(0))
    with f.switch(picked) as arms:
        with arms.case("Red"):
            f.set(answer, u32(10))
        with arms.case("Green"):
            f.set(answer, u32(20))
        with arms.case("Blue"):
            f.set(answer, u32(30))
    f.ret(answer.cast(counter))


@branch("switch-with-a-default", ONE_SIZE)
def _switch_with_a_default(f: FuncBuilder, x: Probe) -> None:
    picked = f.let("sd_picked", x.Colour)
    with f.if_(x.au == u32(1)):
        f.set(picked, x.Colour.Green)
    answer = f.let("sd_answer", u32, u32(7))
    with f.switch(picked) as arms:
        # An arm that does nothing still has to be its own branch, or control
        # would fall into the default.
        with arms.case("Green"):
            pass
        with arms.otherwise():
            f.set(answer, u32(99))
    f.ret(answer.cast(counter))


@branch("break-out-of-a-switch", ONE_SIZE)
def _break_out_of_a_switch(f: FuncBuilder, x: Probe) -> None:
    # A TIR break inside a switch arm belongs to the loop, which is why Go gets
    # a labelled loop and JavaScript an if-chain rather than a switch.
    i = f.let("bs_i", u32, u32(0))
    total = f.let("bs_total", u32, u32(0))
    with f.while_(i < u32(40), (u32(40) - i).cast(counter)):
        picked = f.let("bs_picked", x.Colour)
        with f.if_(i == x.au):
            f.set(picked, x.Colour.Red)
        with f.else_():
            f.set(picked, x.Colour.Green)
        with f.switch(picked) as arms:
            with arms.case("Red"):
                f.brk()
            with arms.otherwise():
                f.set(total, total + u32(1))
        f.set(i, i + u32(1))
    f.ret(shape(i, total))


@branch("take-and-swap")
def _take_and_swap(f: FuncBuilder, x: Probe) -> None:
    left = f.let("ts_left", u32, x.au)
    right = f.let("ts_right", u32, x.bu)
    f.swap(left, right)
    emptied = f.let("ts_emptied", u32, u32(0))
    f.take(emptied, left)
    f.ret(shape(emptied, left))


# --- named constants, which only Go treats as anything special ---
#
# It folds a use of one at compile time and then refuses the overflow TIR
# defines, exactly as it does for a literal, so `tir_k` has to stand between
# the two. Every branch here would be a Go build error without it, which makes
# them the one part of the probe that fails loudly rather than quietly.


@branch("const-u32-add-literal", NO_OPERANDS)
def _const_u32_add_literal(f: FuncBuilder, x: Probe) -> None:
    f.ret((x.BIGU + u32(BIG_U32)).cast(counter))


@branch("const-u32-add-const", NO_OPERANDS)
def _const_u32_add_const(f: FuncBuilder, x: Probe) -> None:
    f.ret((x.BIGU + x.BIGU).cast(counter))


@branch("const-u32-neg", NO_OPERANDS)
def _const_u32_neg(f: FuncBuilder, x: Probe) -> None:
    f.ret((-x.BIGU).cast(counter))


@branch("const-u32-shl", NO_OPERANDS)
def _const_u32_shl(f: FuncBuilder, x: Probe) -> None:
    f.ret(x.BIGU.shl(5).cast(counter))


@branch("const-u32-to-u8", NO_OPERANDS)
def _const_u32_to_u8(f: FuncBuilder, x: Probe) -> None:
    f.ret(x.BIGU.cast(u8).cast(counter))


@branch("const-i32-add", NO_OPERANDS)
def _const_i32_add(f: FuncBuilder, x: Probe) -> None:
    f.ret((x.BIGI + x.BIGI).cast(u32).cast(counter))


@branch("const-i32-neg", NO_OPERANDS)
def _const_i32_neg(f: FuncBuilder, x: Probe) -> None:
    # -MIN is MIN, which is a wrap in TIR and an overflow to Go.
    f.ret((-x.MINI).cast(u32).cast(counter))


@branch("const-u8-add", NO_OPERANDS)
def _const_u8_add(f: FuncBuilder, x: Probe) -> None:
    f.ret((x.BIGB + x.BIGB).cast(counter))


@branch("const-counter-to-u32", NO_OPERANDS)
def _const_counter_to_u32(f: FuncBuilder, x: Probe) -> None:
    # A counter's own arithmetic is a helper call and so never constant, but a
    # cast of one is, and the cap does not fit in a u32.
    f.ret(x.BIGC.cast(u32).cast(counter))


def cases() -> list[tuple[str, int, int, int, int]]:
    """Every case, with the answer the reference interpreter gives."""
    from ..tir.interp import Interpreter

    built = program()
    out = []
    for kind, (name, _, operands) in enumerate(BRANCHES):
        for a, b in operands:
            answer = Interpreter(built).call("probe", [kind, a, b])
            assert isinstance(answer, int)
            out.append((name, kind, a, b, answer))
    return out


def corpus() -> dict:
    """The probe corpus as plain JSON data."""
    return conformance.document(
        NOTE,
        [
            {"name": name, "kind": kind, "a": a, "b": b, "expect": answer}
            for name, kind, a, b, answer in cases()
        ],
        shift=SHIFT,
    )


def corpus_text() -> str:
    return conformance.text(corpus())


@functools.lru_cache(maxsize=1)
def program() -> ir.Program:
    """The probe, built once per process and validated."""
    from ..tir import validate

    built = build()
    validate(built)
    return built


def build() -> ir.Program:
    """The probe, as one TIR program."""
    m = Module()

    pair = m.struct("Pair", [("lo", u32), ("hi", u32)])
    nest = m.struct("Nest", [("pair", pair), ("tag", u32)])
    colour = m.enum("Colour", ["Red", "Green", "Blue"])
    table = m.const("TABLE", frozen(bytes_), TABLE)
    scalars = {
        "BIGU": m.const("BIGU", u32, BIG_U32),
        "BIGI": m.const("BIGI", i32, BIG_I32),
        "MINI": m.const("MINI", i32, MIN_I32),
        "BIGB": m.const("BIGB", u8, BIG_U8),
        "BIGC": m.const("BIGC", counter, CAP),
    }

    bump = m.func("bump", params=[("slot", u32, "inout"), ("by", u32)])
    bump.set(bump["slot"], bump["slot"] + bump["by"])

    swap_pair = m.func("swap_pair", params=[("p", pair, "inout")])
    held = swap_pair.let("held", u32, swap_pair["p"].field("lo"))
    swap_pair.set(swap_pair["p"].field("lo"), swap_pair["p"].field("hi"))
    swap_pair.set(swap_pair["p"].field("hi"), held)

    f = m.func("probe", params=[("kind", u32), ("a", counter), ("b", counter)], ret=counter)
    x = Probe(f, pair, nest, colour, table, scalars)
    for index, (_, emit, _operands) in enumerate(BRANCHES):
        with f.if_(f["kind"] == u32(index)):
            emit(f, x)
    f.ret(counter(0))

    return m.build()


